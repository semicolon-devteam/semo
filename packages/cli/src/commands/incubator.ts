function ensureSessionDir(serviceId: string): string {
  const sessionDir = path.join(sessionsRoot(), serviceId);
  const dirs = [sessionDir, path.join(sessionDir, '.claude'), path.join(sessionDir, 'memory')];
  for (const dir of dirs) {
    fs.mkdirSync(dir, { recursive: true });
  }
  return sessionDir;
}

function createSymlinks(sessionDir: string): void {
  const links: Array<[string, string]> = [
    [SHARED_AGENTS, path.join(sessionDir, '.claude', 'agents')],
    [sharedSkills(), path.join(sessionDir, '.claude', 'skills')],
  ];

  for (const [target, linkPath] of links) {
    if (fs.existsSync(linkPath)) {
      const stat = fs.lstatSync(linkPath);
      if (stat.isSymbolicLink()) fs.unlinkSync(linkPath);
      else continue; // 실제 디렉토리면 건드리지 않음
    }
    if (fs.existsSync(target)) {
      fs.symlinkSync(target, linkPath, 'dir');
    }
  }
}

function writeClaudeMd(
  sessionDir: string,
  serviceId: string,
  serviceName: string,
  channel?: string,
): void {
  const content = `# Incubator Session — ${serviceName}

> Auto-generated by \`semo incubator create\`
> Service ID: ${serviceId}
> Channel: ${channel || '(미할당)'}
> Created: ${new Date().toISOString().slice(0, 10)}

## Context

이 세션은 인큐베이터 프로젝트 **${serviceName}**의 전용 Claude Code 세션이다.

### 라우팅 규칙

유저 메시지를 받으면 아래 우선순위로 봇 Agent를 선택:

1. **명시적 봇 지정**: "디자인팀에게 물어봐" → Agent(designclaw)
2. **현재 Phase 기반**: Dashboard API에서 current_phase 조회 → Phase별 담당 봇 매핑
3. **키워드 분기**: 인프라/배포 → infraclaw, 리뷰/PR → reviewclaw, 마케팅/SEO → growthclaw
4. **폴백**: Agent(semiclaw) — PM/오케스트레이터

Phase → 봇 매핑은 Dashboard API \`GET /api/projects/{service_id}\`의 current_phase에 따름.
봇 프로필은 KB에서 동적 로드됨 (\`semo kb get {botId} slack-config\`).

### 응답 포맷

reply() 호출 시 반드시 \`bot_id\` 파라미터를 전달하여 봇 정체성을 표시.
예: \`reply(text="분석 결과입니다...", bot_id="planclaw", ...)\`
응답 텍스트에 [봇이름] 접두사를 붙이지 않는다 — bot_id가 Slack 표시를 자동 처리.

## KB 도메인

- 서비스 정보: \`semo kb get ${serviceName} base-information\`
- 프로젝트 현황: Dashboard API \`GET /api/gfp/{service_id}\`

## Shared Resources

- Agents: .claude/agents/ (심링크 → 공유)
- Skills: .claude/skills/ (심링크 → 공유)
- KB: semo kb CLI
`;

  fs.writeFileSync(path.join(sessionDir, 'CLAUDE.md'), content, 'utf-8');
}

// channel-slack 패키지 위치. SEMO_REPO_PATH 가 지정되면 그 경로의 packages/channel-slack,
// 아니면 npx 로 실행 (npm 배포 후 `@team-semicolon/channel-slack` 으로 호출 가능).
const CHANNEL_SLACK_DIR = process.env.SEMO_REPO_PATH
  ? path.join(process.env.SEMO_REPO_PATH, 'packages', 'channel-slack')
  : '';

function writeSettingsJson(sessionDir: string, serviceId?: string, channel?: string): void {
  const settings: Record<string, unknown> = {
    permissions: {
      allow: ['Bash(semo kb:*)', 'Bash(semo context:*)', 'Bash(curl:*)', 'Bash(node:*)'],
    },
    hooks: {
      SessionStart: [
        {
          matcher: '',
          hooks: [
            {
              type: 'command',
              command: `. ${semoEnv()} 2>/dev/null; semo context sync 2>/dev/null || true`,
              timeout: 30,
            },
            {
              type: 'command',
              command: `bash ${sharedHooks()}/cron-reregister.sh`,
              timeout: 5000,
            },
          ],
        },
      ],
      Stop: [
        {
          matcher: '',
          hooks: [
            {
              type: 'command',
              command: `. ${semoEnv()} 2>/dev/null; semo context push 2>/dev/null || true`,
              timeout: 30,
            },
          ],
        },
      ],
    },
  };

  fs.writeFileSync(
    path.join(sessionDir, '.claude', 'settings.json'),
    JSON.stringify(settings, null, 2),
    'utf-8',
  );

  // .mcp.json — Channel Slack 플러그인 등록
  // SEMO_REPO_PATH 가 지정되면 source tsx 로 실행, 아니면 npx 로 published 패키지 실행.
  const channelSlackArgs = CHANNEL_SLACK_DIR
    ? ['tsx', path.join(CHANNEL_SLACK_DIR, 'src', 'index.ts')]
    : ['@team-semicolon/channel-slack'];
  const mcpConfig: Record<string, unknown> = {
    mcpServers: {
      'semo-channel-slack': {
        command: 'npx',
        args: channelSlackArgs,
        env: {
          SLACK_CHANNEL_ID: channel || '',
          SEMO_SERVICE_ID: serviceId || '',
        },
      },
    },
  };

  fs.writeFileSync(path.join(sessionDir, '.mcp.json'), JSON.stringify(mcpConfig, null, 2), 'utf-8');
}

