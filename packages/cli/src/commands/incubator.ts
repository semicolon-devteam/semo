interface SessionRecord {
  service_id: string;
  service_name: string;
  channel: string | null;
  session_dir: string;
  status: 'active' | 'stopped' | 'archived';
  created_at: string;
}

async function upsertSessionRecord(
  serviceId: string,
  serviceName: string,
  channel: string | null,
  sessionDir: string,
): Promise<void> {
  const pool = getPool();
  await pool.query(
    `INSERT INTO ${DB_SCHEMA}.incubator_sessions
       (service_id, service_name, channel, session_dir, status)
     VALUES ($1, $2, $3, $4, 'active')
     ON CONFLICT (service_id) DO UPDATE SET
       status = 'active',
       session_dir = $4,
       channel = COALESCE($3, ${DB_SCHEMA}.incubator_sessions.channel)`,
    [serviceId, serviceName, channel, sessionDir],
  );
}

async function updateSessionStatus(
  serviceId: string,
  status: 'active' | 'stopped' | 'archived',
): Promise<void> {
  const pool = getPool();
  await pool.query(`UPDATE ${DB_SCHEMA}.incubator_sessions SET status = $2 WHERE service_id = $1`, [
    serviceId,
    status,
  ]);
}

async function listSessions(): Promise<SessionRecord[]> {
  const pool = getPool();
  const result = await pool.query<SessionRecord>(
    `SELECT service_id, service_name, channel, session_dir, status,
            created_at::text
     FROM ${DB_SCHEMA}.incubator_sessions
     ORDER BY created_at DESC`,
  );
  return result.rows;
}

async function getSession(serviceId: string): Promise<SessionRecord | null> {
  const pool = getPool();
  const result = await pool.query<SessionRecord>(
    `SELECT service_id, service_name, channel, session_dir, status,
            created_at::text
     FROM ${DB_SCHEMA}.incubator_sessions
     WHERE service_id = $1`,
    [serviceId],
  );
  return result.rows[0] || null;
}

