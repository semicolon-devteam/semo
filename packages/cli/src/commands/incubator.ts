function getLaunchdLabel(serviceId: string): string {
  return `com.semo.incubator.${serviceId.slice(0, 8)}`;
}

function writeLaunchdPlist(serviceId: string, sessionDir: string): string {
  fs.mkdirSync(LAUNCHD_DIR, { recursive: true });

  const label = getLaunchdLabel(serviceId);
  const plistPath = path.join(LAUNCHD_DIR, `${label}.plist`);
  const logDir = path.join(sessionDir, 'logs');
  fs.mkdirSync(logDir, { recursive: true });

  const plist = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>${label}</string>
  <key>ProgramArguments</key>
  <array>
    <string>/usr/local/bin/claude</string>
    <string>--resume</string>
    <string>--dangerously-skip-permissions</string>
  </array>
  <key>WorkingDirectory</key>
  <string>${sessionDir}</string>
  <key>EnvironmentVariables</key>
  <dict>
    <key>HOME</key>
    <string>${os.homedir()}</string>
    <key>PATH</key>
    <string>/usr/local/bin:/usr/bin:/bin:/opt/homebrew/bin</string>
  </dict>
  <key>RunAtLoad</key>
  <false/>
  <key>KeepAlive</key>
  <false/>
  <key>StandardOutPath</key>
  <string>${logDir}/stdout.log</string>
  <key>StandardErrorPath</key>
  <string>${logDir}/stderr.log</string>
</dict>
</plist>`;

  fs.writeFileSync(plistPath, plist, 'utf-8');
  return plistPath;
}

