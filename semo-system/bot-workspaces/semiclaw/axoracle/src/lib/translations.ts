export type Lang = keyof typeof t;

/** Get occupation name by language.
 * DB has name_ko, name_en, name_ja (+ name_local for backward compat).
 */
export function getOccupationName(
  occ: { name_en?: string; name_ko?: string; name_ja?: string; name_local?: string },
  lang: Lang
): string {
  if (lang === 'ko') return occ.name_ko || occ.name_local || occ.name_en || '';
  if (lang === 'ja') return occ.name_ja || occ.name_local || occ.name_en || '';
  return occ.name_en || occ.name_local || '';
}

/** Get task name by language */
export function getTaskName(
  task: { name_en?: string; name_kr?: string },
  lang: Lang
): string {
  if (lang === 'ko' && task.name_kr) return task.name_kr;
  return task.name_en || task.name_kr || '';
}

/** Get experience level name by language */
export function getExpLevelName(
  level: { name_ko?: string; name_en?: string; name_ja?: string },
  lang: Lang
): string {
  const map: Record<Lang, string | undefined> = {
    ko: level.name_ko,
    en: level.name_en,
    ja: level.name_ja || level.name_en,
  };
  return map[lang] || level.name_en || '';
}
